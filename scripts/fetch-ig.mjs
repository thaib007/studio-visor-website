// Fill the Recent Works section from Instagram.
// 1) Put post/reel links (one per line) in scripts/ig-links.txt
// 2) node scripts/fetch-ig.mjs   → downloads covers to src/assets/ig and rewrites src/data/works.ts
import fs from "node:fs";
import path from "node:path";
import https from "node:https";

const ROOT = path.resolve(new URL("..", import.meta.url).pathname);
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36";

const get = (url, depth = 0) =>
  new Promise((resolve, reject) => {
    if (depth > 5) return reject(new Error("too many redirects"));
    https
      .get(url, { headers: { "User-Agent": UA, Accept: "text/html,image/*,*/*" } }, (res) => {
        if ([301, 302, 303, 307, 308].includes(res.statusCode)) {
          res.resume();
          return get(new URL(res.headers.location, url).href, depth + 1).then(resolve, reject);
        }
        const chunks = [];
        res.on("data", (c) => chunks.push(c));
        res.on("end", () =>
          resolve({ status: res.statusCode, type: res.headers["content-type"] || "", buf: Buffer.concat(chunks) }),
        );
      })
      .on("error", reject);
  });

const linksFile = path.join(ROOT, "scripts/ig-links.txt");
const links = fs.existsSync(linksFile)
  ? fs.readFileSync(linksFile, "utf8").split(/\s+/).filter((s) => /instagram\.com\/(p|reel)\//.test(s))
  : [];
if (!links.length) {
  console.log("No links found. Add Instagram post/reel URLs to scripts/ig-links.txt (one per line).");
  process.exit(0);
}

fs.mkdirSync(path.join(ROOT, "src/assets/ig"), { recursive: true });
const works = [];
for (const link of links) {
  const code = link.match(/\/(?:p|reel)\/([A-Za-z0-9_-]{11})/)?.[1];
  if (!code || works.some((w) => w.code === code)) continue;
  const page = await get(`https://www.instagram.com/p/${code}/embed/captioned/`);
  const html = page.buf.toString("utf8");
  const img = html.match(/"display_url":"((?:[^"\\]|\\.)*)"/)?.[1]?.replace(/\\u0026/g, "&");
  if (!img) {
    console.log("x", code, "- Instagram asked for a login; try again from a logged-in network or add the image by hand.");
    continue;
  }
  const r = await get(img);
  if (!r.type.startsWith("image")) {
    console.log("x", code, "- cover image blocked");
    continue;
  }
  const file = `w${String(works.length + 1).padStart(2, "0")}`;
  fs.writeFileSync(path.join(ROOT, `src/assets/ig/${file}.jpg`), r.buf);
  works.push({ code, url: `https://www.instagram.com/p/${code}/`, file, video: /\/reel\//.test(link) });
  console.log("ok", code);
}

const out = [
  "// GENERATED by scripts/fetch-ig.mjs from @studio.visor posts.",
  ...works.map((w) => `import ${w.file} from "../assets/ig/${w.file}.jpg?inline";`),
  "",
  "export const IG = \"https://www.instagram.com/studio.visor/\";",
  "",
  "export const IG_BIO =",
  "  \"Helping YT owners · Video editing · Thumbnail design · Full automation production · DM for free fuel\";",
  "",
  "export interface Work { code: string; url: string; image: string; video: boolean; }",
  "",
  "export const WORKS: Work[] = [",
  ...works.map((w) => `  { code: \"${w.code}\", url: \"${w.url}\", image: ${w.file}, video: ${w.video} },`),
  "];",
  "",
].join("\n");
fs.writeFileSync(path.join(ROOT, "src/data/works.ts"), out);
console.log(`Wrote ${works.length} works -> src/data/works.ts`);
